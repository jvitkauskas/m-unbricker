"""Make stage/logo.rs, the helper's screen: art/logo/logo_device.png (480x480, black + 3 colours,
art/logo/logo_device_palette.json) reduced to SIZE x SIZE, run-length coded as the app's pictures
(byte = (run - 1) << 2 | colour index, runs of 1..64)."""
import json, pathlib, sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))


ROOT = pathlib.Path(__file__).resolve().parents[1]
SIZE = 180

import make_art  # noqa: E402
make_art.SIZE = SIZE
pal = json.loads((ROOT / "art/logo/logo_device_palette.json").read_text())
rle, _ = make_art.convert(ROOT / "art/logo/logo_device.png", pal)
rows = [", ".join("0x%02x" % b for b in rle[i:i + 16]) for i in range(0, len(rle), 16)]
out = ["// Generated by tools/make_logo.py from art/logo/logo_device.png (made for M-Unbricker, MIT).",
       "//! The helper's logo: LOGO_SIZE by LOGO_SIZE pixels, a byte for each run of one colour, (run - 1) << 2 | its",
       "//! index in LOGO_PAL (RGB565), row after row.",
       f"pub const LOGO_SIZE: u32 = {SIZE};",
       "pub const LOGO_PAL: [u16; 4] = [" + ", ".join("0x%04X" % make_art.rgb565(c) for c in pal) + "];",
       f"pub const LOGO_RLE: [u8; {len(rle)}] = [\n    " + ",\n    ".join(rows) + ",\n];"]
(ROOT / "stage" / "logo.rs").write_text("\n".join(out) + "\n")
print(f"stage/logo.rs: {SIZE}x{SIZE}, {len(rle)} bytes")
