"""Pack the rescue images (rescue/BOARD/boot.bin, and app.bin if there is one)
into build/rescue_img.h for the RAM program. Without app.bin, everything past
the boot area is erased: m-bootloader then finds no firmware and waits in MIDI mode.

The app area of a JieLi image is encrypted with the chip key (0x980F) per
32-byte block, the key mixed with the block's offset; most of it is padding
(0xFF before encryption). Only the blocks that are not padding are stored;
the program regenerates the rest. The boot area is stored as it is.

  make_images.py RESCUE_DIR OUT.h
"""
import sys, zlib, pathlib

KEY = 0x980F
BOARDS = [("fm1", "FM1", 0, 0), ("smk37", "SMK37", 0xC0000, 0xC2000)]


def keystream(off):
    key = (KEY ^ (off >> 2)) & 0xFFFF
    out = bytearray(32)
    for i in range(32):
        out[i] = key & 0xFF
        key = ((key << 1) ^ (0x1021 if key & 0x8000 else 0)) & 0xFFFF
    return bytes(out)


def fill(off):
    return bytes(0xFF ^ k for k in keystream(off))


def pack(app):
    assert len(app) % 32 == 0
    runs, lit = [], bytearray()
    for b in range(len(app) // 32):
        blk = app[b * 32:b * 32 + 32]
        is_fill = blk == fill(b * 32)
        if runs and runs[-1][2] == (0xFFFFFFFF if is_fill else runs[-1][2]) and runs[-1][0] + runs[-1][1] == b \
                and (is_fill or runs[-1][2] != 0xFFFFFFFF):
            runs[-1][1] += 1
        else:
            runs.append([b, 1, 0xFFFFFFFF if is_fill else len(lit)])
        if not is_fill:
            lit += blk
    return runs, bytes(lit)


def unpack(runs, lit, n):
    out = bytearray()
    for start, count, lo in runs:
        for i in range(count):
            b = start + i
            out += fill(b * 32) if lo == 0xFFFFFFFF else lit[lo + i * 32:lo + i * 32 + 32]
    assert len(out) == n
    return bytes(out)


def carr(name, data):
    rows = [", ".join("0x%02x" % x for x in data[i:i + 16]) for i in range(0, len(data), 16)]
    return "static const u8 %s[%d] __attribute__((aligned(4))) = {\n\t%s\n};\n" % (name, len(data), ",\n\t".join(rows))


def main():
    src, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    h = ["/* Generated by tools/make_images.py from rescue/ (see rescue/README.md). */",
         "#define IMG_KEY 0x%04Xu" % KEY, ""]
    for d, tag, klo, khi in BOARDS:
        boot = (src / d / "boot.bin").read_bytes()
        app_file = src / d / "app.bin"
        app = app_file.read_bytes() if app_file.exists() else b""
        assert len(boot) == 0x4000 and len(app) % 0x1000 == 0
        runs, lit = pack(app)
        assert unpack(runs, lit, len(app)) == app
        if not app:  # C has no empty arrays: a run of no blocks, 32 unused bytes
            runs, lit = [[0, 0, 0xFFFFFFFF]], bytes(32)
        h.append("/* %s: app %d B = %d B stored in %d runs */" % (tag, len(app), len(lit), len(runs)))
        h.append(carr("%s_BOOT" % tag, boot))
        h.append(carr("%s_LIT" % tag, lit))
        h.append("static const u32 %s_RUNS[%d][3] = {\n%s\n};" % (tag, len(runs), ",\n".join(
            "\t{ %d, %d, 0x%X }" % tuple(r) for r in runs)))
        h.append("#define %s_APP_LEN %du" % (tag, len(app)))
        h.append("#define %s_BOOT_CRC 0x%08Xu" % (tag, zlib.crc32(boot)))
        h.append("#define %s_APP_CRC 0x%08Xu" % (tag, zlib.crc32(app)))
        h.append("#define %s_KEEP_LO 0x%Xu\n#define %s_KEEP_HI 0x%Xu\n" % (tag, klo, tag, khi))
        print(tag, "app", len(app), "stored", len(lit), "runs", len(runs))
    out.write_text("\n".join(h) + "\n")


main()
