"""Make src/fonts.h: DejaVu Sans (Bitstream Vera licence, permissive; see
LICENSES/DejaVu-fonts.txt) rendered with 4 levels of antialiasing (2 bits per
pixel) at the sizes the pages use.

  tools/make_fonts.py [DEJAVU_TTF_DIR] (default /usr/share/fonts/truetype/dejavu)
"""
import pathlib, sys
from PIL import Image, ImageDraw, ImageFont

TTF = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu")
OUT = pathlib.Path(__file__).resolve().parents[1] / "src" / "fonts.h"
FONTS = [  # C name, file, pixel size
    ("font_title", "DejaVuSans-Bold.ttf", 20),
    ("font_body", "DejaVuSans.ttf", 16),
    ("font_small", "DejaVuSans.ttf", 13),
]
EXTRA = "▶◀·–—’“”…−✓"
CHARS = [chr(c) for c in range(32, 127)] + list(EXTRA)


def render(path, size):
    font = ImageFont.truetype(str(path), size)
    ascent, descent = font.getmetrics()
    glyphs, bits = [], bytearray()
    for ch in CHARS:
        x0, y0, x1, y1 = font.getbbox(ch)
        adv = round(font.getlength(ch))
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        img = Image.new("L", (max(w, 1), max(h, 1)), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
        px = list(img.getdata()) if w and h else []
        levels = [min(3, (v * 3 + 127) // 255) for v in px]
        off = len(bits)
        acc = n = 0
        for lv in levels:
            acc |= lv << (2 * n)
            n += 1
            if n == 4:
                bits.append(acc)
                acc = n = 0
        if n:
            bits.append(acc)
        glyphs.append((ord(ch), off, w, h, x0, y0, adv))
    return ascent + descent, ascent, glyphs, bytes(bits)


def main():
    out = ["/* Generated by tools/make_fonts.py: DejaVu Sans, 2-bit antialiased glyphs. */",
           "/* DejaVu fonts: Bitstream Vera licence and public domain changes (LICENSES/DejaVu-fonts.txt). */", ""]
    total = 0
    for name, file, size in FONTS:
        height, ascent, glyphs, bits = render(TTF / file, size)
        total += len(bits) + 10 * len(glyphs)
        out.append(f"/* {name}: {file} at {size} px, {len(bits)} bytes of glyphs */")
        rows = [", ".join("0x%02x" % b for b in bits[i:i + 16]) for i in range(0, len(bits), 16)]
        out.append(f"static const u8 {name}_bits[{len(bits)}] = {{\n\t" + ",\n\t".join(rows) + "\n};")
        out.append(f"static const struct glyph {name}_glyphs[{len(glyphs)}] = {{")
        for cp, off, w, h, x0, y0, adv in glyphs:
            out.append(f"\t{{ 0x{cp:04X}, {off}, {w}, {h}, {x0}, {y0}, {adv} }},")
        out.append("};")
        out.append(f"static const struct font {name} = {{ {name}_glyphs, {name}_bits, {len(glyphs)}, {height}, {ascent} }};\n")
    OUT.write_text("\n".join(out) + "\n")
    print(f"{OUT}: {total} bytes of font data")


main()
