"""Make src/art.rs from art/device/NAME.png (480x480, black + 3 colours, see
art/device/palette.json): each picture reduced to 120x120, mapped to its 4
colours, run-length coded (byte = (run - 1) << 2 | index, runs of 1..64).
A missing picture is None (the page is drawn without it)."""
import json, pathlib
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[1]
NAMES = ["welcome", "unplug_pc", "connect", "switch_on", "waking", "found", "checking", "press_play", "repairing",
         "success", "error", "retry", "leave"]
SIZE = 120


def rgb565(h):
    r, g, b = int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16)
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def convert(path, pal):
    rgb = [tuple(int(h[i:i + 2], 16) for i in (1, 3, 5)) for h in pal]
    im = Image.open(path).convert("RGB").resize((SIZE, SIZE), Image.BOX)
    idx = []
    for p in im.getdata():
        idx.append(min(range(4), key=lambda i: sum((a - b) ** 2 for a, b in zip(p, rgb[i]))))
    out, i = bytearray(), 0
    while i < len(idx):
        j = i
        while j < len(idx) and idx[j] == idx[i] and j - i < 64:
            j += 1
        out.append(((j - i - 1) << 2) | idx[i])
        i = j
    return bytes(out), idx


def main():
    dev = ROOT / "art" / "device"
    pals = json.loads((dev / "palette.json").read_text()) if (dev / "palette.json").exists() else {}
    h = ["// Generated by tools/make_art.py from the art/device pictures (made for this project, MIT).",
         "// (Not every picture is on a page.)", "#![allow(dead_code)]",
         "use crate::ui::Pic;", ""]
    total = 0
    for n in NAMES:
        f = dev / f"{n}.png"
        up = n.upper()
        if not f.exists() or n not in pals or len(pals[n]) != 4:
            h.append(f"pub const {up}: Option<&Pic> = None;")
            continue
        rle, _ = convert(f, pals[n])
        total += len(rle)
        rows = [", ".join("0x%02x" % b for b in rle[i:i + 16]) for i in range(0, len(rle), 16)]
        h.append(f"static {up}_RLE: [u8; {len(rle)}] = [" + "".join(f"\n    {r}," for r in rows) + "\n];")
        pal = ", ".join("0x%04X" % rgb565(c) for c in pals[n])
        h.append(f"pub const {up}: Option<&Pic> = Some(&Pic {{ w: {SIZE}, h: {SIZE}, pal: [{pal}], rle: &{up}_RLE }});")
    (ROOT / "src" / "art.rs").write_text("\n".join(h) + "\n")
    print(f"src/art.rs: {total} bytes of pictures")

if __name__ == "__main__":
    main()
