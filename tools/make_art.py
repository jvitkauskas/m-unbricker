"""Make src/art.h from art/device/NAME.png (480x480, black + 3 colours, see
art/device/palette.json): each picture reduced to 120x120, mapped to its 4
colours, run-length coded (byte = (run - 1) << 2 | index, runs of 1..64).
A missing picture is a null pointer (the page is drawn without it)."""
import json, pathlib
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[1]
NAMES = ["welcome_fm1", "welcome_smk37", "unplug_pc_fm1", "unplug_pc_smk37", "connect_fm1", "connect_smk37",
         "switch_on", "waking", "found_fm1", "found_smk37", "checking", "press_play", "repairing",
         "success_fm1", "success_smk37", "error", "retry", "leave"]
SIZE = 120


def rgb565(h):
    r, g, b = int(h[1:3], 16), int(h[3:5], 16), int(h[5:7], 16)
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def convert(path, pal):
    rgb = [tuple(int(h[i:i + 2], 16) for i in (1, 3, 5)) for h in pal]
    im = Image.open(path).convert("RGB").resize((SIZE, SIZE), Image.BOX)
    idx = []
    for p in im.getdata():
        idx.append(min(range(4), key=lambda i: sum((a - b) ** 2 for a, b in zip(p, rgb[i]))))
    out, i = bytearray(), 0
    while i < len(idx):
        j = i
        while j < len(idx) and idx[j] == idx[i] and j - i < 64:
            j += 1
        out.append(((j - i - 1) << 2) | idx[i])
        i = j
    return bytes(out), idx


def main():
    dev = ROOT / "art" / "device"
    pals = json.loads((dev / "palette.json").read_text()) if (dev / "palette.json").exists() else {}
    h = ["/* Generated by tools/make_art.py from the art/device pictures (made for this project, MIT). */", ""]
    total = 0
    for n in NAMES:
        f = dev / f"{n}.png"
        if not f.exists() or n not in pals or len(pals[n]) != 4:
            h.append(f"#define PIC_{n} ((const struct pic *)0)")
            continue
        rle, _ = convert(f, pals[n])
        total += len(rle)
        rows = [", ".join("0x%02x" % b for b in rle[i:i + 16]) for i in range(0, len(rle), 16)]
        h.append(f"static const u8 {n}_rle[{len(rle)}] = {{\n\t" + ",\n\t".join(rows) + "\n};")
        pal = ", ".join("0x%04X" % rgb565(c) for c in pals[n])
        h.append(f"static const struct pic {n}_pic = {{ {SIZE}, {SIZE}, {{ {pal} }}, {n}_rle }};")
        h.append(f"#define PIC_{n} (&{n}_pic)")
    (ROOT / "src" / "art.h").write_text("\n".join(h) + "\n")
    print(f"src/art.h: {total} bytes of pictures")


if __name__ == "__main__":
    main()
